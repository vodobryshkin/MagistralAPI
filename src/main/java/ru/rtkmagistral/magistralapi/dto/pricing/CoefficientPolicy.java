package ru.rtkmagistral.magistralapi.dto.pricing;

/**
 * Правило определения регионального коэффициента для субъекта РФ.
 */
public enum CoefficientPolicy {
    /** Любой адрес субъекта относится к тарифному городу с коэффициентом 1,0. */
    ALWAYS_CENTER,

    /** Любой адрес Ленинградской области получает специальный коэффициент 1,15. */
    ALWAYS_LENINGRAD_REGION,

    /** Любой адрес субъекта считается адресом вне тарифного центра и получает коэффициент 1,25. */
    ALWAYS_REGIONAL,

    /** Тарифный центр получает 1,0, остальные населённые пункты субъекта — 1,25. */
    CENTER_OR_REGIONAL
}
